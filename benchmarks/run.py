"""The benchmark runner. `decis bench` is a thin wrapper around this file.

`AGENTS.md §8` is the reason this exists as a checked-in program rather than a
collection of ad-hoc scripts: **any number in the docs must come from a raw JSON file
in `benchmarks/results/`, and the tables must be generated by `benchmarks/report.py`.**
Nothing here decides what the numbers mean; it only records what happened, in enough
detail that someone else can disagree with the conclusion.

What gets recorded for every sample, because a latency figure without them is not
interpretable (again §8):

    engine, checkpoint, revision, engine version
    device, dtype, threads, processes
    questions per request, state length, input sha256, input token count
    the raw per-sample milliseconds -- not only a summary

Two honest limits, recorded in the output rather than left for the reader to notice:

1. **This measures within-request batching only.** Cross-request batching -- the thing
   `docs/design.md §6` claims is the main throughput lever -- is not implemented until
   Stage 3, so this runner cannot exercise it. `benchmarks/README.md` M5 tracks that,
   and no QPS figure may be published until it has data.
2. **`single_caller_questions_per_second` is not throughput.** It is the rate one
   serial caller achieves: `1000 / (p50_ms / questions)`. It ignores concurrency.

Thread count cannot be changed after torch has initialised, so each thread count is
measured in a **child process**. That is not a convenience: measuring two thread counts
in one process would silently report the first one's setting for both.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import statistics
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

SCHEMA = "decis-benchmark/1"
RESULTS = Path(__file__).resolve().parent / "results"

#: The decision-shaped request the probes and the docs have always used. Keeping it
#: byte-identical across runs is what makes `input_sha256` comparable over time.
STATE: dict[str, Any] = {
    "from": "user@acme.com",
    "subject": "Duplicate charge on invoice #4411",
    "body": ("Hi, we were billed twice for March. Please refund the duplicate today or we will cancel our plan."),
}


def make_questions(count: int) -> dict[str, Any]:
    """`count` questions, rotating choice(4) / score(3) / noul like a real triage call."""
    questions: dict[str, Any] = {}
    for index in range(count):
        kind = index % 3
        if kind == 0:
            questions[f"choice_{index}"] = {
                "type": "choice",
                "instructions": "Which department should handle this request?",
                "criteria": {
                    "billing": "invoices, payments, refunds",
                    "technical": "bugs, outages, system errors",
                    "sales": "pricing, new contracts",
                    "other": "everything else",
                },
            }
        elif kind == 1:
            questions[f"score_{index}"] = {
                "type": "score",
                "instructions": "How urgent is this request?",
                "criteria": ["Not urgent", "Normal", "Urgent", "Critical"],
            }
        else:
            questions[f"noul_{index}"] = {
                "type": "noul",
                "instructions": "Does this message contain a cancellation threat?",
            }
    return questions


def build_payload(engine: str, count: int) -> dict[str, Any]:
    return {"model": engine, "state": STATE, "questions": make_questions(count)}


def canonical_sha256(payload: dict[str, Any]) -> str:
    """Hash of the canonical request. Compared across configurations by `report.py`.

    Sorted keys and no whitespace, so two runs that send the same request hash the
    same regardless of dict ordering.
    """
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def answer_sha256(answers: dict[str, Any]) -> str:
    """Hash of the response answers.

    Recorded so a reader can tell *identical input gave identical output* from
    *identical input gave different output* -- which is the whole question when a
    benchmark compares, say, two thread counts.
    """
    blob = json.dumps(answers, sort_keys=True, separators=(",", ":"), ensure_ascii=False, default=str)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def host_facts() -> dict[str, Any]:
    return {
        "platform": platform.platform(),
        "machine": platform.machine(),
        "cpu_count": os.cpu_count(),
        "mem_gb": round(_total_memory_gb(), 1),
        "gpu": _has_gpu(),
    }


def _total_memory_gb() -> float:
    try:
        pages = os.sysconf("SC_PHYS_PAGES")
        size = os.sysconf("SC_PAGE_SIZE")
        return pages * size / 1024**3
    except (ValueError, OSError, AttributeError):
        return 0.0


def _has_gpu() -> bool:
    try:
        import torch
    except ImportError:
        return False
    if torch.cuda.is_available():
        return True
    return bool(getattr(torch.backends, "mps", None) and torch.backends.mps.is_available())


def runtime_facts() -> dict[str, Any]:
    facts: dict[str, Any] = {"python": platform.python_version()}
    for module in ("torch", "transformers", "laya", "numpy"):
        try:
            facts[module] = __import__(module).__version__
        except ImportError:
            facts[module] = None
    return facts


def peak_rss_gb() -> float:
    import resource

    return round(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024**2, 2)


# --- the child: one thread count, one server, every questions-per-request ---------


def measure_child(engine: str, threads: int, counts: list[int], iterations: int, warmup: int) -> dict[str, Any]:
    """Run in a fresh process and return this thread count's configurations."""
    os.environ["DECIS_TORCH_THREADS"] = str(threads)
    for key in ("NO_PROXY", "no_proxy"):
        os.environ[key] = "127.0.0.1,localhost,::1"

    sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

    import threading

    import uvicorn

    from decis.app import create_app
    from decis.config import Settings

    settings = Settings(api_keys=("bench",), default_engine=engine, torch_threads=threads)
    app = create_app(settings)

    import socket

    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        port = probe.getsockname()[1]

    server = uvicorn.Server(uvicorn.Config(app, host="127.0.0.1", port=port, log_level="warning"))
    thread = threading.Thread(target=server.run, daemon=True, name="bench-server")
    started = time.perf_counter()
    thread.start()

    base = f"http://127.0.0.1:{port}"
    _wait_until_ready(base)
    load_s = round(time.perf_counter() - started, 1)
    rss = peak_rss_gb()
    observed = _loaded_engine_facts(app, engine)

    configs = []
    try:
        for count in counts:
            payload = build_payload(engine, count)
            samples = []
            tokens = 0
            digest = ""
            for index in range(warmup + iterations):
                began = time.perf_counter()
                body = _post(base, payload)
                elapsed = (time.perf_counter() - began) * 1000.0
                if index < warmup:
                    continue
                samples.append(round(elapsed, 3))
                tokens = body["usage"]["input_tokens"]
                digest = answer_sha256(body["answers"])

            configs.append(
                {
                    "threads": threads,
                    "questions_per_request": count,
                    "state_chars": len(json.dumps(STATE, ensure_ascii=False)),
                    "input_sha256": canonical_sha256(payload),
                    "input_tokens": tokens,
                    "answer_sha256": digest,
                    "n": len(samples),
                    "samples_ms": samples,
                    "p50_ms": round(statistics.median(samples), 1),
                    "p95_ms": round(_percentile(samples, 0.95), 1),
                    "min_ms": round(min(samples), 1),
                    "max_ms": round(max(samples), 1),
                    "ms_per_question": round(statistics.median(samples) / count, 1),
                    "single_caller_questions_per_second": round(count / (statistics.median(samples) / 1000.0), 2),
                }
            )
    finally:
        server.should_exit = True
        thread.join(timeout=30)

    return {
        "threads": threads,
        "load_s": load_s,
        "peak_rss_gb": rss,
        "observed": observed,
        "configs": configs,
    }


def _percentile(values: list[float], fraction: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    position = min(len(ordered) - 1, round(fraction * (len(ordered) - 1)))
    return ordered[position]


def _wait_until_ready(base: str, timeout: float = 900.0) -> None:
    import urllib.error
    import urllib.request

    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(f"{base}/readyz", timeout=5) as response:
                if response.status == 200:
                    return
        except urllib.error.HTTPError:
            pass  # 503 loading: keep waiting
        except OSError:
            pass
        time.sleep(0.5)
    raise TimeoutError(f"the engine was not ready within {timeout:.0f}s")


def _loaded_engine_facts(app: Any, engine_id: str) -> dict[str, Any]:
    """What the engine *actually* loaded with, read after readiness.

    Asking the table instead would be wrong for every engine that decides its own
    precision (Laya forces fp32 on cpu/mps and is deliberately absent from
    `DTYPE_DEFAULTS`), and `info().dtype` before `load()` is just "unloaded". This is
    the only place the real device/dtype/version is observable, and §8 requires them
    next to every number.
    """
    try:
        service = app.state.service
        info = service.scheduler.engine.info() if hasattr(service, "scheduler") else service.engine.info()
        return {
            "engine_id": info.id,
            "version": info.version,
            "device": info.device,
            "dtype": info.dtype,
            "max_sequence_tokens": info.max_sequence_tokens,
            "max_question_tokens": info.max_question_tokens,
            "max_state_tokens": info.max_state_tokens,
        }
    except Exception as error:
        return {"engine_id": engine_id, "error": f"{type(error).__name__}: {error}"}


def _post(base: str, payload: dict[str, Any]) -> dict[str, Any]:
    import urllib.request

    request = urllib.request.Request(
        f"{base}/v1/systemone",
        data=json.dumps(payload).encode("utf-8"),
        headers={"content-type": "application/json", "authorization": "Bearer bench"},
    )
    with urllib.request.urlopen(request, timeout=1800) as response:
        return json.loads(response.read())


# --- the parent ------------------------------------------------------------------


def run(engine: str, threads_list: list[int], counts: list[int], iterations: int, warmup: int) -> dict[str, Any]:
    """Spawn one child per thread count and assemble the group document."""
    import sys as _sys

    children = []
    for threads in threads_list:
        print(f"  threads={threads}: measuring {len(counts)} configuration(s)...", file=sys.stderr, flush=True)
        command = [
            _sys.executable,
            str(Path(__file__).resolve()),
            "--child",
            "--engine",
            engine,
            "--threads",
            str(threads),
            "--batch",
            ",".join(str(value) for value in counts),
            "--iterations",
            str(iterations),
            "--warmup",
            str(warmup),
        ]
        result = subprocess.run(command, capture_output=True, text=True, check=False)
        if result.returncode != 0:
            raise SystemExit(f"threads={threads} failed:\n{result.stdout[-2000:]}\n{result.stderr[-2000:]}")
        children.append(json.loads(result.stdout.strip().splitlines()[-1]))

    first = children[0] if children else {}
    return {
        "schema": SCHEMA,
        "group": f"{engine}-cpu-thread-sweep",
        "engine": engine,
        "device": first.get("observed", {}).get("device", "cpu"),
        "dtype": first.get("observed", {}).get("dtype", "unknown"),
        "engine_version": first.get("observed", {}).get("version"),
        "processes": 1,
        "batching": {
            "scope": "within-request",
            "note": (
                "questions_per_request is the within-request batch. Cross-request batching is "
                "not implemented until Stage 3, so this run cannot exercise it -- see "
                "benchmarks/README.md M5. No QPS figure may be published from this data."
            ),
        },
        "state_chars": len(json.dumps(STATE, ensure_ascii=False)),
        "request": {"state": STATE, "questions_per_request": counts},
        "host": host_facts(),
        "runtime": runtime_facts(),
        "load_s": first.get("load_s"),
        "peak_rss_gb": first.get("peak_rss_gb"),
        "methodology_caveats": [
            "Thread counts are measured in separate processes (torch cannot change this after init).",
            "Configurations run in the order given, not randomised: thermal drift is confounded "
            "with thread count. Order-of-magnitude conclusions only.",
            f"n = {iterations} iterations per configuration after {warmup} warmup call(s), reported as median.",
            "Within-request batching only; cross-request batching is unmeasured (M5).",
            "Latency is client-observed over a loopback socket, so it includes HTTP and JSON overhead.",
        ],
        "runs": children,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--engine", default="laya-multilingual", help="engine id, e.g. kev-0.8b")
    parser.add_argument("--threads", default="", help="comma-separated thread counts; default: one per vCPU")
    parser.add_argument("--batch", default="1,3,10,30", help="comma-separated questions per request")
    parser.add_argument("--iterations", type=int, default=8)
    parser.add_argument("--warmup", type=int, default=2)
    parser.add_argument("--out", default="", help="output path; default benchmarks/results/<engine>-thread-sweep.json")
    parser.add_argument("--stdout", action="store_true", help="print the document instead of writing it")
    # Internal: the child measures one thread count and prints its section.
    parser.add_argument("--child", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    counts = [int(value) for value in args.batch.split(",") if value.strip()]
    threads_list = (
        [int(value) for value in args.threads.split(",") if value.strip()] if args.threads else [os.cpu_count() or 1]
    )

    if args.child:
        section = measure_child(args.engine, threads_list[0], counts, args.iterations, args.warmup)
        print(json.dumps(section))
        return 0

    print(f"benchmarking {args.engine}: threads={threads_list} batch={counts}", file=sys.stderr)
    document = run(args.engine, threads_list, counts, args.iterations, args.warmup)

    if args.stdout:
        print(json.dumps(document, indent=2, ensure_ascii=False))
        return 0

    out = Path(args.out) if args.out else RESULTS / f"{args.engine}-thread-sweep.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    try:
        shown = out.resolve().relative_to(Path.cwd())
    except ValueError:
        shown = out  # an out-of-tree --out is legitimate; do not crash on the message
    print(f"wrote {shown}", file=sys.stderr)
    print("regenerate the docs tables with: uv run python benchmarks/report.py --write", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
